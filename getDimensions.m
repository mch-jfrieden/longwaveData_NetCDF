function DimVec = getDimensions(dataSize, dataSizeRaw)
%% This function returns an array containing the usual dimensions contained in structures
% 
arguments
    dataSize {mustBeInteger} = 0
    dataSizeRaw {mustBeInteger} = 0
end

dataSizeRawHalf = int32(dataSizeRaw / 2.);

DimVec.TimeRaw = struct( ...
        'Name',       { 'TimeRaw' }, ...
        'Length',     { dataSizeRaw }, ...
        'Unlimited',  { false } );

DimVec.TimeRawHalf = struct( ...
        'Name',       { 'TimeRawHalf' }, ...
        'Length',     { dataSizeRawHalf }, ...
        'Unlimited',  { false } );

DimVec.Time = struct(...
        'Name',      { 'Time' },...
        'Length',    { dataSize },...
        'Unlimited', { true } );

DimVec.Lon = struct(...
        'Name',      { 'Lon' },...
        'Length',    { 360 },...
        'Unlimited', { false } );

DimVec.Lat = struct(...
        'Name',      { 'Lat' },...
        'Length',    { 180 },...
        'Unlimited', { false } );

DimVec.Coef = struct(...
    'Name',         { 'Coef' }, ...
    'Length',       { 10 }, ...
    'Unlimited',    { false } );

end