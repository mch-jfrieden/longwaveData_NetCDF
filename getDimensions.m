function DimVec = getDimensions(dataSize)
%% This function returns an array containing the usual dimensions contained in structures
% 
arguments
    dataSize {mustBeInteger, mustBePositive} = 0
end

DimVec.Time = struct(...
        'Name',      { 'Time' },...
        'Length',    { dataSize },...
        'Unlimited', { true } );

DimVec.Lon = struct(...
        'Name',      { 'Lon' },...
        'Length',    { 360 },...
        'Unlimited', { false } );

DimVec.Lat = struct(...
        'Name',      { 'Lat' },...
        'Length',    { 180 },...
        'Unlimited', { false } );

DimVec.Coef = struct(...
    'Name',         { 'Coef' }, ...
    'Length',       { 10 }, ...
    'Unlimited',    { false } );

end